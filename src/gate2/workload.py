"""Deterministic, bounded synthetic workload fixtures for Gate 2.

Only generated bytes are represented here. This module has no media, network,
provider, model, filesystem, or clock integration.
"""
from __future__ import annotations

import hashlib
import json
import random
import re
from dataclasses import dataclass


class WorkloadError(ValueError):
    """A requested fixture is invalid or exceeds the local generation bounds."""


_LIMITS = {
    "jobs": (1, 100),
    "stages": (1, 20),
    "artifact_bytes": (1, 1_000_000),
    "cost_units": (1, 1_000_000),
    "concurrency": (1, 1),
    "repetitions": (1, 100),
}
_MAX_TOTAL_ARTIFACT_BYTES = 8_000_000
_SHA40 = re.compile(r"^[0-9a-f]{40}$")
_SHA64 = re.compile(r"^[0-9a-f]{64}$")


@dataclass(frozen=True)
class WorkloadSpec:
    jobs: int
    stages: int
    artifact_bytes: int
    cost_units: int
    fault_position: int
    seed: int
    f01_sha: str
    c04_sha: str
    e05_sha: str
    config_digest: str
    concurrency: int = 1
    repetitions: int = 2

    def __post_init__(self) -> None:
        for name, (minimum, maximum) in _LIMITS.items():
            value = getattr(self, name)
            if isinstance(value, bool) or not isinstance(value, int) or not minimum <= value <= maximum:
                raise WorkloadError(f"{name} must be an integer in [{minimum}, {maximum}]")
        for name in ("seed", "fault_position"):
            value = getattr(self, name)
            if isinstance(value, bool) or not isinstance(value, int):
                raise WorkloadError(f"{name} must be an integer")
        if not 0 <= self.fault_position < self.stages:
            raise WorkloadError("fault_position must index a declared stage")
        if self.jobs * self.stages * self.artifact_bytes > _MAX_TOTAL_ARTIFACT_BYTES:
            raise WorkloadError("total generated artifact bytes exceed 8000000")
        for name in ("f01_sha", "c04_sha", "e05_sha"):
            if not isinstance(getattr(self, name), str) or not _SHA40.fullmatch(getattr(self, name)):
                raise WorkloadError(f"{name} must be a lowercase 40-character SHA")
        if not isinstance(self.config_digest, str) or not _SHA64.fullmatch(self.config_digest):
            raise WorkloadError("config_digest must be a lowercase SHA-256 digest")

    def to_dict(self) -> dict[str, object]:
        return {
            "dimensions": {
                name: getattr(self, name)
                for name in ("jobs", "stages", "artifact_bytes", "cost_units", "fault_position", "concurrency", "repetitions")
            },
            "seed": self.seed,
            "identity": {name: getattr(self, name) for name in ("f01_sha", "c04_sha", "e05_sha", "config_digest")},
        }


@dataclass(frozen=True)
class SyntheticStage:
    stage_index: int
    cost_units: int
    artifact: bytes

    @property
    def artifact_digest(self) -> str:
        return hashlib.sha256(self.artifact).hexdigest()


@dataclass(frozen=True)
class SyntheticJob:
    job_index: int
    stages: tuple[SyntheticStage, ...]


@dataclass(frozen=True)
class SyntheticFixture:
    spec: WorkloadSpec
    jobs: tuple[SyntheticJob, ...]
    fault_schedule: tuple[tuple[int, int, int], ...]
    uses_wall_clock: bool = False

    def to_dict(self) -> dict[str, object]:
        return {
            "schema": "gate2.synthetic-workload.v1",
            **self.spec.to_dict(),
            "uses_wall_clock": False,
            "fault_schedule": [list(point) for point in self.fault_schedule],
            "jobs": [
                {"job_index": job.job_index, "stages": [
                    {"stage_index": stage.stage_index, "cost_units": stage.cost_units,
                     "artifact_hex": stage.artifact.hex(), "artifact_digest": stage.artifact_digest}
                    for stage in job.stages
                ]}
                for job in self.jobs
            ],
        }

    def to_bytes(self) -> bytes:
        return json.dumps(self.to_dict(), sort_keys=True, separators=(",", ":")).encode("utf-8")

    @property
    def fixture_digest(self) -> str:
        return hashlib.sha256(self.to_bytes()).hexdigest()

    @property
    def generation_id(self) -> str:
        return self.fixture_digest


def generate(spec: WorkloadSpec) -> SyntheticFixture:
    if not isinstance(spec, WorkloadSpec):
        raise WorkloadError("spec must be a WorkloadSpec")
    # Salt the declared seed with all identity/dimension fields so even an
    # identity-only change regenerates the deterministic payload bytes.
    identity = json.dumps(spec.to_dict(), sort_keys=True, separators=(",", ":")).encode()
    rng = random.Random(int.from_bytes(hashlib.sha256(identity).digest(), "big"))
    jobs = tuple(
        SyntheticJob(job_index, tuple(
            SyntheticStage(stage_index, spec.cost_units * (stage_index + 1),
                           bytes(rng.randrange(256) for _ in range(spec.artifact_bytes)))
            for stage_index in range(spec.stages)
        ))
        for job_index in range(spec.jobs)
    )
    schedule = tuple(
        (repetition, rng.randrange(spec.jobs), spec.fault_position)
        for repetition in range(spec.repetitions)
    )
    return SyntheticFixture(spec=spec, jobs=jobs, fault_schedule=schedule)
