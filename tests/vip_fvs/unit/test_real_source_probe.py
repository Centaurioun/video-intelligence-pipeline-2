"""RED contract tests for the real-source probe seam.

These tests intentionally use a generated byte fixture and a fake subprocess
runner.  They describe the Gate-0/FVS boundary without opening archive media,
loading a model, or contacting a provider.
"""
from __future__ import annotations

import json
from pathlib import Path

import pytest

from vip_fvs.source_adapter import ProbeFailure, probe_real_source


def _synthetic_source(tmp_path: Path) -> Path:
    path = tmp_path / "generated-source.mp4"
    path.write_bytes(b"test-owned synthetic container bytes")
    return path


def _completed_probe(payload: dict):
    encoded = json.dumps(payload).encode("utf-8")

    class Completed:
        returncode = 0
        stdout = encoded
        stderr = b""

    def runner(argv, **kwargs):
        return Completed()

    return runner


def test_real_probe_captures_pinned_ffprobe_evidence_without_mutating_source(tmp_path):
    source = _synthetic_source(tmp_path)
    before = source.read_bytes()
    observed = {
        "streams": [
            {
                "index": 0,
                "codec_type": "video",
                "time_base": "1/600",
                "duration_ts": "1200",
            }
        ],
        "format": {"format_name": "mov,mp4,m4a,3gp,3g2,mj2"},
    }
    calls: list[list[str]] = []

    def runner(argv, **kwargs):
        calls.append(list(argv))
        return _completed_probe(observed)(argv, **kwargs)

    result = probe_real_source(
        source, executable=tmp_path / "ffprobe", source_revision_id="rev-unit", policy_identity="policy-unit", runner=runner
    )

    assert result.ffprobe_json == observed
    assert result.selected_stream_index == 0
    assert result.time_base == (1, 600)
    assert result.probe_ref
    assert source.read_bytes() == before
    assert calls and calls[0][-1] == str(source)
    assert "-show_streams" in calls[0]
    assert "-show_format" in calls[0]


def test_real_probe_binds_snapshot_path_separately_from_original_locator(tmp_path):
    source = _synthetic_source(tmp_path)
    snapshot = tmp_path / "private" / "snapshots" / "snap-1" / "source.mp4"
    snapshot.parent.mkdir(parents=True)
    snapshot.write_bytes(source.read_bytes())
    evidence = {"snapshot_id": "snap-1", "snapshot_sha256": "a" * 64}
    observed = {"streams": [{"index": 0, "codec_type": "video", "time_base": "1/600"}]}
    calls = []

    result = probe_real_source(
        snapshot, executable=tmp_path / "ffprobe", source_revision_id="rev-snapshot",
        policy_identity="policy-snapshot", runner=lambda argv, **kwargs: (calls.append(list(argv)) or _completed_probe(observed)(argv, **kwargs)),
        source_locator=str(source), snapshot_evidence=evidence,
    )

    assert calls[0][-1] == str(snapshot)
    assert result.source_path == snapshot
    assert result.source_locator == str(source)
    assert result.snapshot_evidence == evidence


def test_real_probe_rejects_probe_process_failure(tmp_path):
    source = _synthetic_source(tmp_path)

    class Failed:
        returncode = 1
        stdout = b""
        stderr = b"synthetic ffprobe failure"

    with pytest.raises(ProbeFailure, match="SOURCE_PROBE_FAILED"):
        probe_real_source(
            source, executable=tmp_path / "ffprobe", source_revision_id="rev-failure", policy_identity="policy-failure",
            runner=lambda *args, **kwargs: Failed(),
        )


def test_real_probe_requires_an_explicit_executable_path(tmp_path):
    source = _synthetic_source(tmp_path)
    observed = {"streams": [{"index": 0, "codec_type": "video", "time_base": "1/600"}]}

    with pytest.raises(TypeError, match="executable"):
        probe_real_source(source, runner=_completed_probe(observed))

    with pytest.raises(ProbeFailure, match="EXPLICIT_EXECUTABLE_REQUIRED"):
        probe_real_source(
            source, executable="ffprobe", source_revision_id="rev-explicit", policy_identity="policy-explicit",
            runner=_completed_probe(observed),
        )


def test_real_probe_requires_nonempty_revision_and_policy_identity(tmp_path):
    source = _synthetic_source(tmp_path)
    observed = {"streams": [{"index": 0, "codec_type": "video", "time_base": "1/600"}]}
    runner = _completed_probe(observed)

    with pytest.raises(ProbeFailure, match="SOURCE_REVISION_REQUIRED"):
        probe_real_source(source, executable=tmp_path / "ffprobe", source_revision_id="", policy_identity="policy", runner=runner)
    with pytest.raises(ProbeFailure, match="POLICY_IDENTITY_REQUIRED"):
        probe_real_source(source, executable=tmp_path / "ffprobe", source_revision_id="rev", policy_identity=" ", runner=runner)


