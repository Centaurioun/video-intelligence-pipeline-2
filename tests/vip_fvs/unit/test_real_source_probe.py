def test_real_probe_fails_closed_when_no_video_stream_is_eligible(tmp_path):
    source = _synthetic_source(tmp_path)
    payload = {"streams": [{"index": 0, "codec_type": "audio"}], "format": {}}

    with pytest.raises(ProbeFailure, match="NO_ELIGIBLE_VIDEO_STREAM"):
        probe_real_source(
            source, executable=tmp_path / "ffprobe", source_revision_id="rev-no-video", policy_identity="policy-no-video",
            runner=_completed_probe(payload),
        )
