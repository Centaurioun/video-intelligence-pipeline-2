_ZERO_DIGEST = "0" * 64
_MP4_BYTES = build_mp4(
    media_timescale=1000,
    sample_deltas=(40, 40, 80, 80),
    ctts_offsets=(0, 80, -40, -40),
)
_THREAT_MODEL = (
    "protects_against_other_users_and_accidental_changes_not_malicious_same_user_processes"
)


def _digest(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def _store(tmp_path: Path, name: str = "snapshot-store") -> SourceSnapshotStore:
    return SourceSnapshotStore(
        tmp_path / name, max_source_bytes=64_000, max_store_bytes=128_000
    )


def _capture_bytes(
    tmp_path: Path,
    content: bytes,
    *,
    name: str = "synthetic-source.bin",
    revision: str | None = "revision:claimed",
    authorization_id: str = "authorization:synthetic",
    store_name: str = "snapshot-store",
):
    source = tmp_path / name
    source.write_bytes(content)
    store = _store(tmp_path, store_name)
    snapshot = store.capture(
        source,
        expected_sha256=_digest(content),
        authorization_id=authorization_id,
        source_revision_id=revision,
    )
    return store, source, snapshot


def _capture_mp4(
    tmp_path: Path,
    *,
    revision: str = "revision:manifest-captured",
    authorization_id: str = "authorization:synthetic",
    store_name: str = "snapshot-store",
):
    return _capture_bytes(
        tmp_path,
        _MP4_BYTES,
        name="synthetic-source.mp4",
        revision=revision,
        authorization_id=authorization_id,
        store_name=store_name,
    )


def _private_rewrite(path: Path, data: bytes) -> None:
    """Rewrite a 0o400 evidence file while preserving the store's permission model."""
    path.chmod(0o600)
    path.write_bytes(data)
    path.chmod(0o400)


def _forge_manifest(snapshot, **overrides: object) -> None:
    """Rewrite the manifest body, recomputing only its *internal* self-digest.

    ``snapshot.manifest_sha256`` (the value the caller holds) is intentionally
    left stale, so this models an on-disk tamper rather than a consistent
    re-capture.
    """
    manifest = json.loads(snapshot.manifest_path.read_text())
    manifest.update(overrides)
    body = dict(manifest)
    body.pop("manifest_sha256", None)
    manifest["manifest_sha256"] = _digest(
        json.dumps(body, sort_keys=True, separators=(",", ":"), ensure_ascii=False).encode()
    )
    encoded = (
        json.dumps(manifest, sort_keys=True, separators=(",", ":"), ensure_ascii=False) + "\n"
    ).encode()
    _private_rewrite(snapshot.manifest_path, encoded)


def _probe_binding(source: Path, *, sha256: str, byte_count: int) -> RealSourceProbeBinding:
    return RealSourceProbeBinding(
        source_path=source,
        source_revision_id="revision:claimed",
        source_sha256=sha256,
        source_byte_count=byte_count,
        selected_stream_index=0,
        timebase_num=1,
        timebase_den=1000,
        ffprobe_json={"streams": [{"index": 0, "codec_type": "video"}]},
        probe_digest="a" * 64,
        probe_artifact_ref="probe:canonical",
        raw_probe_artifact_ref="probe:raw",
        canonical_probe_artifact_ref="probe:canonical",
    )


def _write_refinement_artifact(tmp_path: Path, record: dict) -> Path:
    artifact = tmp_path / "refinement-artifact.json"
    artifact.write_text(
        json.dumps(record, sort_keys=True, separators=(",", ":"), ensure_ascii=False) + "\n"
    )
    return artifact


