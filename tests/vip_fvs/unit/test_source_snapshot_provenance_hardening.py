def test_symlinked_component_and_non_regular_sources_are_refused(tmp_path: Path) -> None:
    content = b"synthetic-symlink-test-bytes"
    real_dir = tmp_path / "real-dir"
    real_dir.mkdir()
    real_file = real_dir / "bytes.bin"
    real_file.write_bytes(content)

    # Final component is a symlink: lstat-based no-follow check refuses it.
    final_link = tmp_path / "final-link.bin"
    final_link.symlink_to(real_file)
    with pytest.raises(SourceSnapshotError, match="SOURCE_PATH_NOT_REGULAR_NOFOLLOW"):
        _store(tmp_path).capture(
            final_link,
            expected_sha256=_digest(content),
            authorization_id="authorization:synthetic",
        )

    # Parent component is a symlink: the path resolves elsewhere, so capture
    # refuses a substituted path.  (macOS caveat: paths under /tmp are already
    # substituted because /tmp -> /private/tmp; pytest's tmp_path is resolved,
    # so this only exercises the explicit link created here.)
    linked_dir = tmp_path / "linked-dir"
    linked_dir.symlink_to(real_dir, target_is_directory=True)
    linked_source = linked_dir / "bytes.bin"
    assert linked_source.resolve(strict=True) != linked_source
    with pytest.raises(SourceSnapshotError, match="SOURCE_PATH_SUBSTITUTED"):
        _store(tmp_path).capture(
            linked_source,
            expected_sha256=_digest(content),
            authorization_id="authorization:synthetic",
        )

    # Non-regular files never become snapshots.
    directory_source = tmp_path / "a-directory"
    directory_source.mkdir()
    fifo_source = tmp_path / "a-fifo"
    os.mkfifo(fifo_source)
    for candidate in (directory_source, fifo_source):
        assert stat.S_ISREG(candidate.lstat().st_mode) is False
        with pytest.raises(SourceSnapshotError, match="SOURCE_PATH_NOT_REGULAR_NOFOLLOW"):
            _store(tmp_path).capture(
                candidate,
                expected_sha256=_ZERO_DIGEST,
                authorization_id="authorization:synthetic",
            )


