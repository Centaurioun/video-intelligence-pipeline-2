def test_evidence_digest_is_sha256_of_captured_bytes(tmp_path: Path) -> None:
    content = b"synthetic-source-bytes-v1"
    store, source, snapshot = _capture_bytes(tmp_path, content)
    evidence = snapshot.as_evidence()

    # The digest is computed over the captured bytes themselves, not over a
    # caller-supplied string and not over the live source metadata.
    expected = _digest(content)
    assert snapshot.sha256 == expected == evidence["snapshot_sha256"]
    assert snapshot.byte_count == len(content) == evidence["source_byte_count"]
    assert snapshot.snapshot_path.read_bytes() == content
    assert store.verify(snapshot) is None

    manifest = json.loads(snapshot.manifest_path.read_text())
    assert manifest["snapshot_sha256"] == expected
    assert manifest["source_byte_count"] == len(content)
    assert manifest["retention"] == "retain_while_evidence_replayable"
    assert manifest["threat_model"] == _THREAT_MODEL

    schema = json.loads(Path("schemas/vip_fvs/source_snapshot.v1.json").read_text())
    assert set(evidence) == set(schema["required"])
    # The schema records no capture timestamp; do not invent one.
    assert "captured_at" not in schema["properties"]
    assert "captured_at" not in evidence
    assert source.read_bytes() == content


def test_same_size_live_source_rewrite_is_detected_by_capture_and_consumer_check(
    tmp_path: Path,
) -> None:
    original = b"synthetic-source-bytes"
    store, source, snapshot = _capture_bytes(tmp_path, original)
    rewritten = b"SYNTHETIC-SOURCE-BYTES"  # same length, different content
    assert len(rewritten) == len(original) and rewritten != original
    source.write_bytes(rewritten)

    # The private copy is the authoritative evidence input: rewriting the live
    # file after capture does not change the verified snapshot identity.
    assert store.verify(snapshot) is None
    assert snapshot.sha256 == _digest(original)
    assert snapshot.snapshot_path.read_bytes() == original

    # A new capture that still claims the old digest refuses on the bytes.
    with pytest.raises(SourceSnapshotError, match="SOURCE_DIGEST_MISMATCH"):
        _store(tmp_path, "fresh-store").capture(
            source,
            expected_sha256=snapshot.sha256,
            authorization_id="authorization:synthetic",
        )

    # The probe consumer path re-reads the named source before use.
    binding = _probe_binding(
        source, sha256=snapshot.sha256, byte_count=snapshot.byte_count
    )
    with pytest.raises(ProbeFailure, match="SOURCE_DIGEST_MISMATCH"):
        assert_source_unchanged(binding)


def test_same_size_snapshot_rewrite_is_refused_by_verify_and_evidence_verifier(
    tmp_path: Path,
) -> None:
    content = b"synthetic-source-bytes"
    store, _source, snapshot = _capture_bytes(tmp_path, content)
    _private_rewrite(snapshot.snapshot_path, b"X" * len(content))

    with pytest.raises(SourceSnapshotError, match="SNAPSHOT_DIGEST_MISMATCH"):
        store.verify(snapshot)
    with pytest.raises(SourceSnapshotError, match="SNAPSHOT_DIGEST_MISMATCH"):
        verify_snapshot_evidence(snapshot.as_evidence())


