def test_revision_id_is_verbatim_provenance_not_byte_identity(tmp_path: Path) -> None:
    content = b"synthetic-revision-bound-bytes"
    store_a, _source_a, snapshot_a = _capture_bytes(
        tmp_path, content, revision="revision:claimed-verbatim", store_name="store-a"
    )
    store_b, _source_b, snapshot_b = _capture_bytes(
        tmp_path, content, revision="revision:other-label", store_name="store-b"
    )

    # The caller string is retained verbatim in both the dataclass and manifest.
    assert snapshot_a.source_revision_id == "revision:claimed-verbatim"
    assert snapshot_a.as_evidence()["source_revision_id"] == "revision:claimed-verbatim"
    assert json.loads(snapshot_a.manifest_path.read_text())["source_revision_id"] == (
        "revision:claimed-verbatim"
    )

    # Identical bytes under a different revision label have the same identity
    # digest: the digest, not the revision string, is the identity authority.
    assert snapshot_a.sha256 == snapshot_b.sha256 == _digest(content)
    assert snapshot_a.byte_count == snapshot_b.byte_count
    assert snapshot_a.snapshot_path.parent.name != snapshot_b.snapshot_path.parent.name

    # The same revision label over different bytes does *not* preserve identity.
    store_c, _source_c, snapshot_c = _capture_bytes(
        tmp_path,
        b"different-bytes",
        name="other-source.bin",
        revision="revision:claimed-verbatim",
        store_name="store-c",
    )
    assert snapshot_c.source_revision_id == snapshot_a.source_revision_id
    assert snapshot_c.sha256 != snapshot_a.sha256

    # The revision string is manifest-bound provenance: a mismatched pair is
    # refused rather than silently trusted.
    with pytest.raises(SourceSnapshotError, match="SNAPSHOT_MANIFEST_MISMATCH"):
        store_a.verify(replace(snapshot_a, source_revision_id="revision:forged"))
    forged_evidence = snapshot_a.as_evidence()
    forged_evidence["source_revision_id"] = "revision:forged"
    with pytest.raises(SourceSnapshotError, match="SNAPSHOT_MANIFEST_BINDING_MISMATCH"):
        verify_snapshot_evidence(forged_evidence)
    assert store_c.verify(snapshot_c) is None


def test_bundle_and_receipt_carry_both_revision_strings_and_bind_by_digest(
    tmp_path: Path,
) -> None:
    store, _source, snapshot = _capture_mp4(
        tmp_path, revision="revision:manifest-captured"
    )
    # A deliberately mismatched caller revision: the refinement request (and
    # therefore the bundle/refinement envelope) declares a different label than
    # the one recorded by capture in the manifest.
    caller_revision = "revision:caller-declared"
    refinement = _refine_snapshot(snapshot, source_revision_id=caller_revision)
    artifact = _write_refinement_artifact(tmp_path, refinement)
    payload = _v3_payload(
        snapshot=snapshot,
        artifact=artifact,
        refinement=refinement,
        source_revision_id=caller_revision,
    )

    bundle = ReviewBundle.create(
        payload,
        run_id="run:synthetic",
        bundle_id="bundle:synthetic",
        created_at="1970-01-01T00:00:00Z",
    )
    record = bundle.to_record()
    assert record["record_schema_version"] == "vip_fvs.review_bundle.v3"

    source = record["payload"]["source"]
    embedded = source["snapshot"]
    # Both provenance strings are carried explicitly; neither is silently
    # normalised to the other.
    assert source["source_revision_id"] == caller_revision
    assert embedded["source_revision_id"] == "revision:manifest-captured"
    assert source["source_revision_id"] != embedded["source_revision_id"]

    # ... and the digest is what actually binds the embedded snapshot.
    assert source["source_sha256"] == embedded["snapshot_sha256"] == snapshot.sha256
    assert source["source_byte_count"] == embedded["source_byte_count"]
    assert source["source_locator"] == embedded["source_locator"]
    assert embedded["snapshot_id"] == snapshot.snapshot_path.parent.name
    assert embedded["authorization_id"] == "authorization:synthetic"
    assert Path(embedded["snapshot_path"]).parent.parent.parent == (
        tmp_path / "snapshot-store"
    )
    assert "captured_at" not in embedded
    # The bundle's only timestamp is a caller-supplied created_at, not a
    # manifest-recorded capture time.
    assert record["payload"]["created_at"] == "1970-01-01T00:00:00Z"

    # Digest authority: swapping the source digest refuses even when the
    # revision strings stay untouched.
    forged_digest = json.loads(json.dumps(record))
    forged_digest["payload"]["source"]["source_sha256"] = _ZERO_DIGEST
    with pytest.raises(ValueError, match="snapshot identity does not match source"):
        ReviewBundle.from_record(forged_digest)

    # Tampering with the embedded evidence digest is refused by the snapshot
    # verifier rather than being trusted as provenance.
    forged_snapshot = json.loads(json.dumps(record))
    forged_snapshot["payload"]["source"]["snapshot"]["snapshot_sha256"] = _ZERO_DIGEST
    with pytest.raises(SourceSnapshotError, match="SNAPSHOT_DIGEST_MISMATCH"):
        ReviewBundle.from_record(forged_snapshot)

    # Serialized bundle evidence round-trips and re-verifies after reload.
    bundle_path = save_review_bundle(bundle, tmp_path / "out" / "review-bundle.json")
    reloaded = load_review_bundle(bundle_path)
    assert reloaded.to_record() == record
    assert reloaded.dependency_digest == bundle.dependency_digest
    assert verify_snapshot_evidence(reloaded.payload["source"]["snapshot"]) is None

    # The preparation receipt propagates the same explicit pair and snapshot
    # evidence, and re-verifies after its own canonical reload.
    result = SimpleNamespace(
        bundle=bundle,
        bundle_path=bundle_path,
        probe=SimpleNamespace(probe_artifact_ref="probe:synthetic", probe_digest="b" * 64),
    )
    receipt = build_preparation_receipt(
        result, run_id="run:synthetic", attempt_id="attempt:synthetic"
    )
    assert receipt.record["schema"] == "vip_fvs.real_receipt.v2"
    receipt_source = receipt.record["source"]
    assert receipt_source["source_revision_id"] == caller_revision
    assert receipt_source["snapshot"]["source_revision_id"] == "revision:manifest-captured"
    assert receipt_source["snapshot"] == snapshot.as_evidence()
    assert receipt_source["snapshot"]["authorization_id"] == "authorization:synthetic"
    assert receipt_source["snapshot"]["source_byte_count"] == snapshot.byte_count
    assert Path(receipt_source["snapshot"]["snapshot_path"]).parent.parent.parent == (
        tmp_path / "snapshot-store"
    )
    assert "captured_at" not in receipt_source["snapshot"]

    receipt_path = save_real_receipt(receipt, tmp_path / "out" / "receipt.json")
    loaded_receipt = load_real_receipt(receipt_path)
    assert loaded_receipt.record_digest == receipt.record_digest
    assert loaded_receipt.record["source"]["snapshot"] == snapshot.as_evidence()
    assert verify_snapshot_evidence(loaded_receipt.record["source"]["snapshot"]) is None

    forged_receipt = json.loads(json.dumps(receipt.to_record()))
    forged_receipt.pop("record_digest")
    forged_receipt["source"]["snapshot"]["snapshot_sha256"] = _ZERO_DIGEST
    with pytest.raises(ValueError):
        RealReceipt.create(forged_receipt)

    assert store.verify(snapshot) is None


