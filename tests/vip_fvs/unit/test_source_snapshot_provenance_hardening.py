def test_verify_temporal_authority_refuses_after_store_mutation_and_tamper(
    tmp_path: Path,
) -> None:
    store, _source, snapshot = _capture_mp4(tmp_path, store_name="temporal-store")
    binding = store.bind_temporal_authority(
        snapshot,
        selected_stream_index=0,
        declared_vfr=True,
        declared_reordering=True,
    )
    evidence = binding.as_evidence()
    assert store.verify_temporal_authority(snapshot, evidence) == binding

    # Truncation of the private copy is refused when the evidence is consumed.
    _private_rewrite(snapshot.snapshot_path, _MP4_BYTES[:-10])
    with pytest.raises(SourceSnapshotError, match="SNAPSHOT_DIGEST_MISMATCH"):
        store.verify_temporal_authority(snapshot, evidence)

    # Same-size content tamper (digest change without a size change) is refused.
    same_size_store, _src, same_size_snapshot = _capture_mp4(
        tmp_path, store_name="same-size-store", revision="revision:same-size"
    )
    same_size_evidence = same_size_store.bind_temporal_authority(
        same_size_snapshot,
        selected_stream_index=0,
        declared_vfr=True,
        declared_reordering=True,
    ).as_evidence()
    original_bytes = same_size_snapshot.snapshot_path.read_bytes()
    _private_rewrite(
        same_size_snapshot.snapshot_path,
        original_bytes[:-1] + bytes([original_bytes[-1] ^ 0x01]),
    )
    with pytest.raises(SourceSnapshotError, match="SNAPSHOT_DIGEST_MISMATCH"):
        same_size_store.verify_temporal_authority(same_size_snapshot, same_size_evidence)

    # A rewritten-but-internally-consistent manifest is detected by the held
    # manifest digest before the temporal evidence can bind again.
    manifest_store, _src2, manifest_snapshot = _capture_mp4(
        tmp_path, store_name="manifest-store", revision="revision:manifest"
    )
    manifest_evidence = manifest_store.bind_temporal_authority(
        manifest_snapshot,
        selected_stream_index=0,
        declared_vfr=True,
        declared_reordering=True,
    ).as_evidence()
    _forge_manifest(manifest_snapshot, threat_model="tamper_was_here")
    with pytest.raises(SourceSnapshotError, match="SNAPSHOT_MANIFEST_DIGEST_MISMATCH"):
        manifest_store.verify_temporal_authority(manifest_snapshot, manifest_evidence)


def test_documented_threat_model_boundary_is_point_in_time_verification(
    tmp_path: Path,
) -> None:
    module_text = Path("src/vip_fvs/source_snapshot.py").read_text()
    package_doc = source_snapshot_module.__doc__ or ""

    # The documented limitation is asserted verbatim: no full-immunity claim.
    assert "not a malicious process under this user" in package_doc
    assert "not a malicious process under this user" in module_text
    assert _THREAT_MODEL in module_text
    assert "Revalidate snapshot bytes and manifest immediately before consumption" in (
        module_text
    )
    assert "tamper-proof" not in module_text.lower()
    assert "full immunity" not in module_text.lower()

    # The manifest itself records the same narrowed threat model.
    store, _source, snapshot = _capture_bytes(tmp_path, b"threat-model-bytes")
