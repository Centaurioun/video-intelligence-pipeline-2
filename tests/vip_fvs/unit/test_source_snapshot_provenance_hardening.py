"""Provenance/identity hardening invariants for the verified source-snapshot stack.

These tests pin the documented identity contract of the real-source custody
boundary using generated bytes only (no archive/media/model/provider access):

1. Byte identity: evidence ``snapshot_sha256`` is the SHA-256 of the captured
   bytes, and the private copy is what later consumers re-verify.
2. Revision binding: a caller-supplied ``source_revision_id`` is recorded
   verbatim as provenance, but the digest remains the identity authority.  A
   record may therefore carry a revision string that differs from the one in
   the manifest; downstream schemas bind the snapshot by locator/digest/size
   and carry both strings explicitly (they are not silently trusted).
3. No-follow / file type: a symlinked final component, a symlinked parent
   component, and non-regular files are refused with the production codes.
   Note the macOS caveat: ``/tmp`` is itself a symlink to ``/private/tmp``, so
   a path that merely passes through such a substituted component cannot be
   captured; ``tmp_path`` from pytest is already resolved.
4. TOCTOU limits: verification is a point-in-time revalidation.  After a
   store mutation/truncation/tamper the verify APIs refuse, but the documented
   threat model only claims protection against accidental changes and other
   users, not against a malicious process running as this user.
5. Consumer semantics: the v3 ReviewBundle and v2 RealReceipt carry snapshot
   id, digest, size, store root, locator, revision, and authorization id; both
   sealed records round-trip through their canonical JSON loaders and the
   embedded snapshot evidence re-verifies after reload.  No capture timestamp
   (``captured_at``) exists in the snapshot evidence schema - that absence is
   asserted here rather than papered over.
"""
