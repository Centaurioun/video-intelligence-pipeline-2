def test_source_mutation_after_capture_does_not_change_authoritative_probe_bytes(tmp_path, monkeypatch):
    source = _source(tmp_path)
    run_dir = tmp_path / "run"
    original = source.read_bytes()
    observed = {}

    def probe(path, **kwargs):
        snapshot_path = Path(path)
        observed.update(path=snapshot_path, evidence=kwargs["snapshot_evidence"])
        measured = _probe(snapshot_path, run_dir)
        return __import__("dataclasses").replace(
            measured, source_locator=kwargs["source_locator"],
            snapshot_evidence=kwargs["snapshot_evidence"],
        )

    monkeypatch.setattr("vip_fvs.real_source_service.probe_real_source", probe)

    class Authorized:
        source_path = source
        index_root = tmp_path / "index"
        output_root = tmp_path / "out"

    def mutate_before_retrieval(*args, **kwargs):
        source.write_bytes(b"mutated fixture bytes")
        assert args[0].source_path == observed["path"]
        assert args[0].source_path.read_bytes() == original
        return type("Retrieved", (), {"space_id": semantic_space_id(_runtime().semantic_space),
                                     "generation_id": "generation-test", "hits": ()})()

    monkeypatch.setattr("vip_fvs.real_source_service.retrieve_local_semantic", mutate_before_retrieval)
    request = RealSourceRequest(
        source_path=source,
        query="target phrase",
        authorization=_auth(source, Authorized.index_root, Authorized.output_root, _runtime()),
        runtime=_runtime(),
        index_root=Authorized.index_root,
        output_root=Authorized.output_root,
        run_dir=run_dir,
        source_revision_id="rev-generated-1",
        attempt_id="attempt-1",
        model_root=tmp_path / "model", source_snapshot_root=tmp_path / "snapshot-store",
        max_source_bytes=1_000_000, max_store_bytes=2_000_000,
    )
    with pytest.raises(RealSourcePreparationRefusal, match="NO_SEMANTIC_MATCH"):
        prepare_real_source(request)
    assert observed["path"] != source
    assert observed["path"].read_bytes() == original


def test_service_passes_explicit_probe_executable(tmp_path, monkeypatch):
    source = _source(tmp_path)
    runtime = _runtime()
    measured = _probe(source, tmp_path / "run")
    observed = {}

    def probe(*args, **kwargs):
        observed.update(kwargs)
        return __import__("dataclasses").replace(
            _probe(Path(args[0]), tmp_path / "run"),
            source_locator=kwargs["source_locator"],
            snapshot_evidence=kwargs["snapshot_evidence"],
        )

    monkeypatch.setattr("vip_fvs.real_source_service.probe_real_source", probe)
    monkeypatch.setattr(
        "vip_fvs.real_source_service.retrieve_local_semantic",
        lambda *args, **kwargs: type("Retrieved", (), {"space_id": semantic_space_id(runtime.semantic_space), "generation_id": "generation-test", "hits": ()})(),
    )
    request = RealSourceRequest(
        source_path=source, query="target phrase", authorization=_auth(source, tmp_path / "index", tmp_path / "out", runtime), runtime=runtime,
        index_root=tmp_path / "index", output_root=tmp_path / "out", run_dir=tmp_path / "run",
        source_revision_id="rev-generated-1", attempt_id="attempt-1", probe_executable=Path("/opt/tools/ffprobe"),
        probe_timeout_seconds=None,
        model_root=tmp_path / "model", source_snapshot_root=tmp_path / "snapshot-store",
        max_source_bytes=1_000_000, max_store_bytes=2_000_000,
    )
    with pytest.raises(RealSourcePreparationRefusal, match="NO_SEMANTIC_MATCH"):
        prepare_real_source(request)
    assert observed["executable"] == Path("/opt/tools/ffprobe")
    assert observed["timeout_seconds"] is None


