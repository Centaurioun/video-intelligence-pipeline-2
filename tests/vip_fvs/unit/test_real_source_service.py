def test_real_service_never_treats_synthetic_preflight_as_real_admission(tmp_path, monkeypatch):
    import sys
    unit_dir = str(Path(__file__).resolve().parent)
    sys.path.insert(0, unit_dir)
    try:
        from test_corpus_admission import _valid_synthetic_attestation
        attestation, synthetic_authorization = _valid_synthetic_attestation()
    finally:
        sys.path.remove(unit_dir)
    from vip_fvs.corpus_admission import AdmissionBinding, check_synthetic_preflight

    source = _source(tmp_path)
    runtime = _runtime()
    binding = AdmissionBinding("candidate-c", "d" * 64, synthetic_authorization, str(source))
    preflight = check_synthetic_preflight(
        (attestation,), bindings=(binding,), operation="prepare-real", output_root=tmp_path / "out",
    )
    request = RealSourceRequest(
        source_path=source, query="target phrase", authorization={"source_sha256": "d" * 64},
        runtime=runtime, index_root=tmp_path / "index", output_root=tmp_path / "out",
        run_dir=tmp_path / "run", source_revision_id="candidate-c", attempt_id="attempt-1",
        model_root=tmp_path / "model", source_snapshot_root=tmp_path / "snapshot-store",
        max_source_bytes=1_000_000, max_store_bytes=2_000_000,
        synthetic_preflight=preflight, admission_bindings=(binding,),
    )
    monkeypatch.setattr(
        "vip_fvs.real_source_service.SourceSnapshotStore.capture",
        lambda *args, **kwargs: pytest.fail("synthetic result reached controlled source snapshot"),
    )
    original_read_bytes = Path.read_bytes
    monkeypatch.setattr(Path, "read_bytes", lambda path: (
        pytest.fail("synthetic result caused controlled source read")
        if path == source else original_read_bytes(path)
    ))
    from vip_fvs.corpus_admission import CorpusAdmissionError
    with pytest.raises(CorpusAdmissionError, match="CORPUS_SEPARATION_REAL_ADMISSION_FORBIDDEN"):
        prepare_real_source(request)


def test_real_service_rejects_nonboolean_revocation_before_snapshot_capture(tmp_path, monkeypatch):
    source = _source(tmp_path)
    runtime = _runtime()
